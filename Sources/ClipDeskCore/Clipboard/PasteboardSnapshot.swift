import Foundation

/// An immutable copy of the general pasteboard's contents at one `changeCount`.
///
/// Mirrors the pasteboard's structure: a snapshot contains one or more items, and each item
/// contains one or more representations (type identifier + bytes) of the same content.
public struct PasteboardSnapshot: Sendable, Equatable {
    public struct Representation: Sendable, Equatable {
        public var type: String
        public var data: Data

        public init(type: String, data: Data) {
            self.type = type
            self.data = data
        }
    }

    public struct Item: Sendable, Equatable {
        public var representations: [Representation]

        public init(representations: [Representation]) {
            self.representations = representations
        }

        public func data(for type: String) -> Data? {
            representations.first { $0.type == type }?.data
        }

        public var types: [String] { representations.map(\.type) }
    }

    public var items: [Item]
    public var changeCount: Int
    public var capturedAt: Date
    public var sourceApp: SourceApplication?
    /// Types that were present on the pasteboard but not read (too large, unreadable or redundant).
    public var omittedTypes: [String]

    public init(
        items: [Item],
        changeCount: Int = 0,
        capturedAt: Date = Date(),
        sourceApp: SourceApplication? = nil,
        omittedTypes: [String] = []
    ) {
        self.items = items
        self.changeCount = changeCount
        self.capturedAt = capturedAt
        self.sourceApp = sourceApp
        self.omittedTypes = omittedTypes
    }

    public var totalByteCount: Int {
        items.reduce(0) { $0 + $1.representations.reduce(0) { $0 + $1.data.count } }
    }
}

/// Well-known pasteboard type identifiers used by the clipboard engine.
public enum PasteboardTypes {
    public static let plainText = "public.utf8-plain-text"
    public static let utf16PlainText = "public.utf16-plain-text"
    public static let utf16ExternalPlainText = "public.utf16-external-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"
    public static let urlName = "public.url-name"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let pdf = "com.adobe.pdf"

    /// Added to items that ClipDesk writes, so the monitor can recognize its own writes.
    public static let restoreMarker = "io.github.sobirmurodkhanovich.clipdesk.restored"

    /// Markers that apps use to say content must not be kept in clipboard history.
    /// See https://nspasteboard.org. These are public conventions, not private APIs.
    public static let privacyMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
    ]

    /// Types ClipDesk understands and restores with full fidelity.
    public static let knownTypes: Set<String> = [
        plainText, utf16PlainText, utf16ExternalPlainText, rtf, rtfd, html,
        fileURL, url, urlName, png, tiff, jpeg, pdf,
        "public.heic", "com.compuserve.gif", "org.webmproject.webp", "com.microsoft.bmp",
        "public.plain-text", "public.utf8-tab-separated-values-text",
        "com.apple.webarchive", "public.vcard",
    ]

    /// File promises make the source app write files when read; they are never read eagerly.
    public static func isFilePromise(_ type: String) -> Bool {
        type.hasPrefix("com.apple.pasteboard.promised") || type.hasPrefix("com.apple.NSFilePromise")
    }

    /// Human-readable name for a type identifier, for the details panel.
    public static func displayName(for type: String) -> String {
        switch type {
        case plainText, utf16PlainText, utf16ExternalPlainText, "public.plain-text": "Plain Text"
        case rtf: "Rich Text (RTF)"
        case rtfd: "Rich Text with Attachments"
        case html: "HTML"
        case fileURL: "File URL"
        case url: "URL"
        case urlName: "URL Title"
        case png: "PNG"
        case tiff: "TIFF"
        case jpeg: "JPEG"
        case pdf: "PDF"
        case "public.heic": "HEIC"
        case "com.compuserve.gif": "GIF"
        case "com.apple.webarchive": "Web Archive"
        default: type
        }
    }
}
